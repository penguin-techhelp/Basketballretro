// LocalStorage Persistence Helper
const FRANCHISE_STORAGE_KEY = 'retro_hoops_95_franchise_v1';

export function loadFranchise(): FranchiseSave {
  try {
    const raw = localStorage.getItem(FRANCHISE_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed.inventory && parsed.coins !== undefined) {
        return parsed;
      }
    }
  } catch (err) {
    console.warn('Failed to load franchise from localStorage', err);
  }

  // Initial fresh franchise
  const starterRoster = createStarterRoster();
  const initialSave: FranchiseSave = {
    teamName: 'Harlem Dynamos',
    coins: 750, // Starter budget
    inventory: starterRoster,
    activeLineupIds: starterRoster.slice(0, 5).map(p => p.id),
    unlockedDivision: 1,
    trophiesWon: [],
    packs: {
      bronze: 2,
      silver: 1,
      gold: 0,
      allStar: 0,
    },
    highScores: {
      threePoint: 14,
      dunkContest: 42,
    },
  };
  saveFranchise(initialSave);
  return initialSave;
}

export function saveFranchise(save: FranchiseSave) {
  try {
    localStorage.setItem(FRANCHISE_STORAGE_KEY, JSON.stringify(save));
  } catch (err) {
    console.error('Failed to save franchise', err);
  }
}
